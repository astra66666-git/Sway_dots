
#!/usr/bin/env bash

# Rofi Theme Changer

dir="$HOME/.config/rofi"
theme_dir="$dir/colors"
shared_dir="$dir/shared"
style="$dir/theme-changer/theme-changer-style.rasi"
colors_file="$shared_dir/colors.rasi"

# Check dependencies
for cmd in rofi find basename awk sed sort; do
    command -v "$cmd" >/dev/null 2>&1 || exit 1
done

# Find available themes
themes=()

while IFS= read -r -d '' file; do
    themes+=("$(basename "$file" .rasi)")
done < <(
    find "$theme_dir" -maxdepth 1 -type f -name '*.rasi' -print0 | sort -z
)

[[ ${#themes[@]} -eq 0 ]] && exit 1

# Current theme
current=$(sed -n 's|.*colors/\([^"]*\)\.rasi.*|\1|p' "$colors_file" | head -n 1)

# Build menu
menu=""

for name in "${themes[@]}"; do
    if [[ "$name" == "$current" ]]; then
        printf -v label '  ●  %s (current)' "$name"
    else
        printf -v label '  ○  %s' "$name"
    fi
    menu+="$label"$'\n'
done

# Show Rofi
chosen=$(printf '%s' "$menu" | rofi \
    -dmenu -i \
    -p "THEMES" \
    -mesg "Choose your color scheme" \
    -theme "$style")

[[ -z "$chosen" ]] && exit 0

selected=$(printf '%s\n' "$chosen" |
    sed -E 's/^[[:space:]]*[●○][[:space:]]+//; s/ \(current\)$//')

[[ -f "$theme_dir/$selected.rasi" ]] || exit 1

selected_colors="$theme_dir/$selected.rasi"

# Extract colors
get_color() {
    local key="$1"
    local fallback="$2"
    local value

    value=$(awk -v key="$key" '
        $1 == key ":" {
            gsub(/;/, "", $2)
            print $2
            exit
        }
    ' "$selected_colors")

    [[ "$value" =~ ^#[[:xdigit:]]{6}([[:xdigit:]]{2})?$ ]] || value="$fallback"

    if [[ ${#value} -eq 9 ]]; then
        value="${value:0:7}"
    fi

    printf '%s' "$value"
}

bg=$(get_color background "#282c34")
bg_alt=$(get_color background-alt "#353b45")
fg=$(get_color foreground "#abb2bf")
selected_color=$(get_color selected "#61afef")
active=$(get_color active "#98c379")
urgent=$(get_color urgent "#e06c75")

# =========================================
# Generate Rofi colors
# =========================================

printf '@import "~/.config/rofi/colors/%s.rasi"\n' "$selected" \
    > "$colors_file.tmp"

mv "$colors_file.tmp" "$colors_file"

# =========================================
# Generate SwayNC colors
# =========================================

swaync_colors="$HOME/.config/swaync/theme-colors.css"

cat > "$swaync_colors.tmp" <<EOF
/* Automatically generated by Rofi Theme Changer */

@define-color bg $bg;
@define-color bg_alt $bg_alt;
@define-color fg $fg;
@define-color selected $selected_color;
@define-color active $active;
@define-color urgent $urgent;
EOF

mv "$swaync_colors.tmp" "$swaync_colors"

# =========================================
# Generate Waybar colors
# =========================================

waybar_colors="$HOME/.config/waybar/theme-colors.css"

cat > "$waybar_colors.tmp" <<EOF
/* Automatically generated by Rofi Theme Changer */

@define-color bg $bg;
@define-color bg_alt $bg_alt;
@define-color fg $fg;
@define-color selected $selected_color;
@define-color active $active;
@define-color urgent $urgent;
EOF

mv "$waybar_colors.tmp" "$waybar_colors"

# =========================================
# Generate Foot colors
# =========================================

foot_colors="$HOME/.config/foot/theme-colors.ini"

foot_bg="${bg#\#}"
foot_bg_alt="${bg_alt#\#}"
foot_fg="${fg#\#}"
foot_selected="${selected_color#\#}"
foot_active="${active#\#}"
foot_urgent="${urgent#\#}"

cat > "$foot_colors.tmp" <<EOF
# Automatically generated by Rofi Theme Changer

[colors-dark]
background=$foot_bg
foreground=$foot_fg

# Normal colors
regular0=$foot_bg_alt
regular1=$foot_urgent
regular2=$foot_active
regular3=$foot_selected
regular4=$foot_selected
regular5=$foot_urgent
regular6=$foot_active
regular7=$foot_fg

# Bright colors
bright0=$foot_fg
bright1=$foot_urgent
bright2=$foot_active
bright3=$foot_selected
bright4=$foot_selected
bright5=$foot_urgent
bright6=$foot_active
bright7=$foot_fg
EOF

mv "$foot_colors.tmp" "$foot_colors"

# =========================================
# Generate Sway window colors
# =========================================

sway_colors="$HOME/.config/sway/theme-colors.conf"

cat > "$sway_colors.tmp" <<EOF
# Automatically generated by Rofi Theme Changer

client.focused          $selected_color $selected_color $foot_fg $selected_color $selected_color
client.focused_inactive $bg_alt $bg_alt $fg $bg_alt $bg_alt
client.unfocused        $bg $bg $fg $bg $bg
client.urgent           $urgent $urgent $foot_fg $urgent $urgent
EOF

mv "$sway_colors.tmp" "$sway_colors"

# =========================================
# Reload everything AFTER generating files
# =========================================

# Run reloads independently of Waybar's click process
setsid -f bash -c '
    sleep 1

    swaync-client --reload-css 2>/dev/null || true

    pkill -SIGUSR2 -x waybar 2>/dev/null || true

    swaymsg reload 2>/dev/null || true
' </dev/null >/dev/null 2>&1

notify-send "Rofi Theme Changer" \
    "Theme changed to $selected" 2>/dev/null

exit 0
